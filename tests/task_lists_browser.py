"""Task Lists in disposable browser storage; no personal profile is used."""
import json
import time


def run_task_checks(*, cdp, evaluate, check, wait_for, add, shot, origin):
    e, q = evaluate, json.dumps
    japan = add('Japan')
    photos = add('Photos', japan)
    places = add('Places', japan)
    e('physics.pause();autoFitPending=false;camera.stopAnimation()')

    def select(id, opened=True):
        e(f'closeContentMenus();closeContextMenu();selectEntry(entries.get({q(id)}),nodes.get({q(id)}),{{reframe:false,openInspector:{str(opened).lower()}}});physics.pause()')

    def click(selector):
        e(f'document.querySelector({q(selector)}).click();applicationCommandTail')

    def submit(name, tasks=None):
        e(f'fields[0].value={q(name)};' + (f'document.getElementById("task-list-tasks").value={q(tasks)};' if tasks is not None else '') + 'fields[0].dispatchEvent(new Event("input"));form.requestSubmit();applicationCommandTail')
        wait_for('!formSaveBusy')

    def create_list(name, parent=japan, tasks=''):
        e(f'createChildEntry({q(parent)},true)')
        submit(name, tasks)
        check(e('!dialog.open'), 'Task List creation closes after durable save: '+name)
        return e('selectedNode.dataset.entryId')

    def done(id, value):
        select(id)
        e(f'var taskCheck=document.getElementById("content-task-done");taskCheck.checked={str(value).lower()};taskCheck.dispatchEvent(new Event("change",{{bubbles:true}}));applicationCommandTail')
        wait_for('camera.frame===null')

    def move(id, destination):
        check(e(f'moveSidebarEntries({{ids:[{q(id)}],activeId:{q(id)}}},{q(destination)})'), 'valid Move succeeds')
        e('physics.pause()')

    def menu_labels():
        return e("[...addMenu.querySelectorAll('button:not([hidden])')].map(b=>b.textContent)")

    select(japan)
    click('#entry-add-button')
    check(menu_labels()[:2] == ['Add item','Add task list'], 'desktop header exposes direct sibling creation actions')
    click('#add-child-button')
    check(e("dialog.open&&!creatingTaskList&&document.getElementById('task-list-fields').hidden"), 'Add item opens normal form without type picker')
    click('#cancel-add-entry')
    select(japan)
    e(f'openContextMenu({q(japan)},600,200)')
    check(e("[...contextMenu.querySelectorAll('button:not([hidden])')].slice(0,2).map(b=>b.textContent).join('|')==='Add item|Add task list'"), 'desktop context exposes sibling Task List action')
    check(e("!document.querySelector('[data-action=task-mode]')"), 'old enable/disable conversion actions removed')
    e('closeContextMenu()');click('#entry-add-button');click('#add-menu [data-add=task-list]')
    check(e("dialog.open&&creatingTaskList&&document.getElementById('add-entry-title').textContent==='Task List'&&!document.getElementById('task-list-fields').hidden"), 'focused Task List dialog opens directly')
    submit('   ', 'Buy flight')
    check(e('dialog.open'), 'Task List requires a nonblank name')
    before=e('entries.size')
    submit('Before the trip', 'x'*61)
    check(e(f'dialog.open&&entries.size==={before}&&!formError.hidden'), 'invalid initial task saves no partial list')
    e('window.taskSave=universeRepository.save;universeRepository.save=async()=>{throw new Error("Test storage failure")}')
    submit('Before the trip', 'Buy flight')
    check(e(f'dialog.open&&entries.size==={before}&&formError.textContent.includes("Test storage failure")'), 'failed creation saves no parent or tasks and keeps draft')
    e('universeRepository.save=taskSave')
    submit('Before the trip', ' Buy flight \n\nBook hotel\n  \nRent car\nBuy eSIM ')
    check(e('!dialog.open'), 'parent and initial tasks created in one flow')
    trip=e('selectedNode.dataset.entryId')
    children=e(f'galaxyModel.childrenOf(entries,{q(trip)}).map(x=>x.id)')
    flight,hotel,car,esim=children
    check(e(f'entries.get({q(trip)}).taskList===true&&galaxyModel.childrenOf(entries,{q(trip)}).map(x=>x.name).join("|") === "Buy flight|Book hotel|Rent car|Buy eSIM"'), 'blank lines ignored; trimmed task names in direct hierarchy')
    check(e(f'{q(children)}.every(id=>entries.get(id).completed===false&&taskStates.get(id).task)'), 'all direct tasks start unchecked')
    check(e(f'[{q(japan)},{q(photos)},{q(places)}].every(id=>!taskStates.get(id).enabled&&!nodes.get(id).hasAttribute("data-task-state"))'), 'Japan, Photos and Places stay completely normal')
    check(e(f'taskStates.get({q(trip)}).ratio===0&&!taskStates.get({q(trip)}).task&&document.getElementById("content-task-control").hidden&&!document.getElementById("content-task-progress").hidden'), 'list shows 0% progress, no Done checkbox')
    def place_scene():
        positions={japan:[390,160], photos:[390,330], places:[390,510], trip:[800,300], flight:[620,510], hotel:[750,510], car:[880,510], esim:[1010,510]}
        e(f"""physics.pause();camera.stopAnimation();autoFitPending=false;
            entries.forEach((entry,id)=>{{const xy=({q(positions)})[id]||[-20000,-20000],p=physics.particles.get(id);entry.x=p.x=xy[0];entry.y=p.y=xy[1]}});
            camera.setView({{x:0,y:0,scale:1}},false);renderGraph();physics.pause();""")
    place_scene()
    check(e(f'getComputedStyle(nodes.get({q(trip)}).querySelector(".task-progress-ring")).display!=="none"'), 'Task List parent keeps visible progress ring')
    shot('task-list-japan-empty-progress')
    e('window.taskPulses=[];window.originalTaskPulse=motion.taskComplete.bind(motion);motion.taskComplete=(node,delay)=>{taskPulses.push(node?.dataset.entryId);return originalTaskPulse(node,delay)}')
    for i,child in enumerate(children):
        done(child,True)
        place_scene()
        if i==1:
            wait_for(f'Math.abs(parseFloat(getComputedStyle(nodes.get({q(trip)}).querySelector(".task-dormant-surface")).opacity)-.5)<.02')
            check(e(f'Math.abs(parseFloat(getComputedStyle(nodes.get({q(trip)}).querySelector(".task-dormant-surface")).opacity)-.5)<.02'), 'parent dormant layer interpolates at 50%')
            select(trip);shot('task-list-japan-half-progress')
        check(e(f'taskStates.get({q(trip)}).ratio==={(i+1)/4}&&nodes.get({q(trip)}).style.getPropertyValue("--task-ratio")==={q(str((i+1)/4).rstrip("0").rstrip(".") if (i+1)/4 != 1 else "1")}'), 'direct progress and parent artwork ratio: '+str(i+1)+'/4')
        check(e(f'nodes.get({q(child)}).dataset.taskComplete==="true"'), 'completed task becomes alive')
        if i<3: check(e(f'!taskPulses.includes({q(trip)})'), 'parent celebration waits for final task')
    check(e(f'taskPulses.includes({q(trip)})&&taskStates.get({q(trip)}).complete'), 'final completion pulses list parent')
    select(trip);time.sleep(.5);shot('task-list-japan-completed')
    e('window.taskIndexCalls=0;window.originalTaskIndex=cosmosTasks.index;cosmosTasks.index=function(...args){taskIndexCalls++;return originalTaskIndex.apply(this,args)};for(let i=0;i<30;i++)renderGraph()')
    check(e('taskIndexCalls===0'), 'render frames never rebuild task metadata')
    e('cosmosTasks.index=originalTaskIndex')
    count=e('taskPulses.length')
    done(flight,False)
    check(e(f'taskPulses.length==={count}&&taskStates.get({q(trip)}).ratio===.75&&nodes.get({q(flight)}).dataset.taskComplete==="false"'), 'uncheck returns task to dormant and lowers progress with no celebration')
    select(flight)
    check(e('!document.getElementById("content-task-control").hidden&&document.getElementById("content-task-progress").hidden'), 'task Contents shows native Done, no parent progress section')
    e('document.getElementById("content-task-done").focus()')
    cdp.call('Input.dispatchKeyEvent',type='keyDown',key=' ',code='Space',windowsVirtualKeyCode=32)
    cdp.call('Input.dispatchKeyEvent',type='keyUp',key=' ',code='Space',windowsVirtualKeyCode=32)
    e('applicationCommandTail')
    check(e(f'entries.get({q(flight)}).completed'), 'native Done supports Space keyboard activation')
    e(f'createChildEntry({q(flight)})')
    check(e('!dialog.open'), 'direct task cannot start child creation')
    select(flight);click('#entry-add-button')
    check('Add item' not in menu_labels() and 'Add task list' not in menu_labels(), 'task desktop + hides prohibited hierarchy creation')
    check(e("['content-add-files','content-notes-empty','content-add-bookmark','content-add-location'].every(id=>!!document.getElementById(id))"), 'task content creation remains available through direct sections')
    e('closeContentMenus()')
    e(f'openContextMenu({q(flight)},600,200)')
    check(e("contextMenu.querySelector('[data-action=add-child]').hidden&&contextMenu.querySelector('[data-action=add-task-list]').hidden"), 'task context hides CB creation')
    e('closeContextMenu()')
    e(f'(async()=>{{await saveEntryContent({q(hotel)},c=>({{...c,notes:{{format:"plain",text:"Booking details"}},links:[{{id:"task-link",url:"https://example.com/"}}]}}));await saveEntryLocation({q(hotel)},{{text:"Tokyo Station"}});}})()')
    check(e(f'entries.get({q(hotel)}).content.notes.text==="Booking details"&&entries.get({q(hotel)}).content.links.length===1&&entries.get({q(hotel)}).location.text==="Tokyo Station"'), 'task retains Notes, Links and Location saving')
    select(photos)
    check(e('document.getElementById("content-task-section").hidden'), 'regular Contents has no task section')
    empty=create_list('Empty list')
    check(e(f'taskStates.get({q(empty)}).ratio===0&&!taskStates.get({q(empty)}).complete&&document.getElementById("content-task-count").textContent==="0 tasks"'), 'zero-task list remains dormant and displays 0 tasks')
    select(empty);click('#entry-add-button')
    check(menu_labels()[0]=='Add task' and 'Add task list' not in menu_labels(), 'list + offers Add task without nested Task List')
    click('#add-child-button');submit('First task')
    check(e(f'entries.get(selectedNode.dataset.entryId).parentId==={q(empty)}&&taskStates.get(selectedNode.dataset.entryId).task'), 'Add task creates direct checkable child')
    select(flight)
    move(flight,photos)
    check(e(f'!taskStates.get({q(flight)}).enabled&&entries.get({q(flight)}).completed'), 'task moved outside becomes normal while retaining completion')
    move(flight,empty)
    check(e(f'taskStates.get({q(flight)}).task&&taskStates.get({q(flight)}).complete'), 'task moved between lists retains completion')
    move(places,trip)
    check(e(f'taskStates.get({q(places)}).task'), 'normal leaf moved into list becomes task')
    move(places,japan);move(flight,trip)
    branch=add('Album',photos);add('Photo',branch)
    check(e(f'!!galaxyModel.movePlan(entries,[{q(branch)}],{q(trip)}).error'), 'Move rejects CB with children into Task List')
    check(e(f'!!galaxyModel.movePlan(entries,[{q(trip)}],{q(empty)}).error'), 'Move rejects Task List inside Task List')
    check(e(f'!new MoveDestinationIndex(entries,{q(trip)}).allowed({q(empty)})&&!new MoveDestinationIndex(entries,{q(hotel)}).allowed({q(car)})'), 'Move picker filters invalid list/task destinations')
    move(trip,places)
    check(e(f'entries.get({q(trip)}).taskList&&taskStates.get({q(hotel)}).task'), 'Task List moves with direct tasks intact')
    move(trip,japan)
    select(trip);e(f'openDuplicateStructure({q(trip)});structureName.value="Next trip";structureForm.requestSubmit();applicationCommandTail')
    wait_for('!structureBusy')
    duplicate=e('selectedNode.dataset.entryId')
    check(e(f'entries.get({q(duplicate)}).taskList&&galaxyModel.childrenOf(entries,{q(duplicate)}).length===4&&galaxyModel.childrenOf(entries,{q(duplicate)}).every(x=>x.completed===false)'), 'Duplicate structure keeps list/tasks and resets completion')
    select(hotel);e(f'copyHierarchyItems([{q(hotel)}]);openHierarchyPaste({q(photos)})')
    click('#hierarchy-paste-copy');wait_for('!pasteBusy')
    pasted=e('selectedNode.dataset.entryId')
    check(e(f'!taskStates.get({q(pasted)}).enabled&&!entries.get({q(pasted)}).taskList'), 'independent task paste outside a list becomes regular CB')
    # Every creative role remains available without adding descendants below tasks.
    deep=add('Deep',branch)
    satellite_list=create_list('Satellite list',deep,'Satellite task')
    satellite=e(f'galaxyModel.childrenOf(entries,{q(satellite_list)})[0].id')
    # branch is depth 2, deep depth 3, list depth 4, task depth 5 (Astronaut).
    check(e(f'entries.get({q(satellite)}).role==="astronaut"&&!!nodes.get({q(satellite)}).querySelector(".task-dormant-art")'), 'Astronaut task retains alien dormant artwork')
    moon_list=create_list('Moon list',branch,'Satellite task')
    sat=e(f'galaxyModel.childrenOf(entries,{q(moon_list)})[0].id')
    check(e(f'entries.get({q(sat)}).role==="satellite"&&!!nodes.get({q(sat)}).querySelector(".task-dormant-art")'), 'Satellite task retains asteroid dormant artwork')
    done(sat,True);done(satellite,True)
    check(e(f'[{q(sat)},{q(satellite)}].every(id=>nodes.get(id).style.getPropertyValue("--task-ratio")==="1")'), 'asteroid and alien transform to normal art when complete')
    e('motion.setReducedMotion(true)');count=e('taskPulses.length');done(esim,False);done(esim,True)
    check(e('motion.reduced&&motion.animations.size===0'), 'reduced motion keeps task completion animation-free')
    for width,height in [(360,800),(390,844),(430,932)]:
        cdp.call('Emulation.setDeviceMetricsOverride',width=width,height=height,deviceScaleFactor=1,mobile=True)
        cdp.call('Emulation.setTouchEmulationEnabled',enabled=True,maxTouchPoints=5)
        wait_for('hierarchySidebar.narrow')
        e('new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))')
        e('closeInspector();hierarchySidebar.setCollapsed(true)');select(japan,False)
        click('#mobile-body-add')
        check(menu_labels()==['Take a photo','Add photo','Add files','Add item','Add task list'], 'mobile quick menu direct choices/order at '+str(width))
        shot('task-list-mobile-menu-'+str(width))
        click('#add-child-button')
        check(e('dialog.open&&!creatingTaskList&&document.getElementById("task-list-fields").hidden'), 'mobile Add item stays direct at '+str(width))
        click('#cancel-add-entry');select(japan,False);click('#mobile-body-add');click('#add-menu [data-add=task-list]')
        check(e('dialog.open&&creatingTaskList'), 'mobile Add task list opens focused creation directly at '+str(width))
        check(e('(()=>{const r=dialog.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&dialog.scrollWidth<=dialog.clientWidth})()'), 'Task List form fits '+str(width)+'px')
        submit('Phone list '+str(width),'Phone task\n\nSecond task')
        phone=e('selectedNode.dataset.entryId')
        check(e(f'entries.get({q(phone)}).taskList&&galaxyModel.childrenOf(entries,{q(phone)}).length===2'), 'mobile creates parent and initial tasks at '+str(width))
        select(trip,False);click('#mobile-body-add')
        check(menu_labels()==['Take a photo','Add photo','Add files','Add task'], 'mobile Task List + offers contextual Add task at '+str(width))
        select(hotel,False);click('#mobile-body-add')
        check(menu_labels()==['Take a photo','Add photo','Add files'], 'task keeps mobile capture without CB creation at '+str(width))
        e('closeContentMenus();hierarchySidebar.setCollapsed(false)')
        check(e(f'hierarchySidebar.rows.get({q(hotel)}).querySelector(".tree-add").hidden&&hierarchySidebar.rows.get({q(hotel)}).querySelector(".tree-more").getClientRects().length>0'), 'mobile task row keeps management without + at '+str(width))
        e('closeContentMenus();hierarchySidebar.setCollapsed(true);openMobileContents()')
        check(e("mobileContents.state==='browse'&&!document.getElementById('content-task-control').hidden"), 'task Done available in mobile Contents at '+str(width))
        shot('task-list-mobile-contents-'+str(width))
    # Reload actual persistence rather than merely inspecting an in-memory snapshot.
    e(f'window.savedTaskFixture={q(dict(trip=trip,hotel=hotel))};localStorage.setItem("task-list-test-fixture",JSON.stringify(savedTaskFixture))')
    cdp.call('Page.reload',ignoreCache=True)
    wait_for("document.readyState==='complete'&&typeof taskStates!=='undefined'&&entries.size>0")
    check(e(f'entries.get({q(trip)}).taskList&&entries.get({q(hotel)}).completed&&taskStates.get({q(hotel)}).task'), 'browser reload preserves Task Lists and completion')
    check(not cdp.errors, 'no Task List browser exceptions')
