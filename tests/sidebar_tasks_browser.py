"""Native desktop/touch sidebar completion using disposable browser storage."""
import json


def run_sidebar_task_checks(*, cdp, e, check, wait_for, add, shot):
    q=json.dumps
    root=add('Sidebar review')
    normal=add('Regular leaf',root)
    e(f'createChildEntry({q(root)},true);fields[0].value="Before the trip";document.getElementById("task-list-tasks").value={q(chr(10).join(["Buy flight","Book hotel","Rent car","Buy eSIM"]))};form.requestSubmit();applicationCommandTail')
    wait_for('!dialog.open&&!formSaveBusy')
    trip=e('selectedNode.dataset.entryId')
    tasks=e(f'galaxyModel.childrenOf(entries,{q(trip)}).map(x=>x.id)')
    flight,hotel,car,esim=tasks
    e(f'hierarchySidebar.expanded=new Set([{q(root)},{q(trip)}]);hierarchySidebar.render();hierarchySidebar.setCollapsed(false);physics.pause();camera.stopAnimation();autoFitPending=false')

    def row(id): return f'.hierarchy-row[data-entry-id="{id}"]'
    def marker(id): return row(id)+' .tree-disclosure'
    def checked(id): return e(f'document.querySelector({q(marker(id))}).getAttribute("aria-checked")')

    def click(selector,touch=False):
        e(f'document.querySelector({q(selector)}).scrollIntoView({{block:"nearest"}});new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))')
        p=e(f'(()=>{{const r=document.querySelector({q(selector)}).getBoundingClientRect();return {{x:r.x+r.width/2,y:r.y+r.height/2}}}})()')
        if touch:
            cdp.call('Input.dispatchTouchEvent',type='touchStart',touchPoints=[p])
            cdp.call('Input.dispatchTouchEvent',type='touchEnd',touchPoints=[])
        else:
            cdp.call('Input.dispatchMouseEvent',type='mousePressed',button='left',clickCount=1,**p)
            cdp.call('Input.dispatchMouseEvent',type='mouseReleased',button='left',clickCount=1,**p)
        e('applicationCommandTail');wait_for('camera.frame===null')

    def select(id):
        e(f'selectEntry(entries.get({q(id)}),nodes.get({q(id)}),{{reframe:false,openInspector:!hierarchySidebar.narrow}});hierarchySidebar.setCollapsed(false);camera.stopAnimation();physics.pause()')

    def layout(id):
        return e(f'(()=>{{const r=document.querySelector({q(row(id))}),n=r.querySelector(".tree-name").getBoundingClientRect(),s=r.querySelector(".tree-disclosure-slot").getBoundingClientRect(),b=r.querySelector(".tree-disclosure").getBoundingClientRect();return {{name:n.left,row:r.getBoundingClientRect().height,gutter:s.width,button:[b.width,b.height],center:b.left+b.width/2,slotCenter:s.left+s.width/2,nameClear:b.right<=n.left,columns:getComputedStyle(r).gridTemplateColumns,children:r.children.length}}}})()')

    for id in tasks:
        check(checked(id)=='false','direct task starts with an unchecked sidebar marker')
        check(e(f'document.querySelector({q(marker(id))}).getAttribute("role")==="checkbox"'),'task marker exposes checkbox role')
    for id in [root,normal,trip]:
        check(e(f'!document.querySelector({q(row(id))}).querySelector("[role=checkbox]")'),'normal/List parent row has no task checkbox')
    check(e(f'document.querySelector({q(row(trip))}).hasAttribute("aria-expanded")&&!document.querySelector({q(marker(trip))}).disabled'),'Task List parent retains ordinary disclosure')
    check(e(f'document.querySelector({q(marker(normal))}).disabled&&getComputedStyle(document.querySelector({q(marker(normal))})).visibility==="hidden"'),'normal leaf keeps reserved invisible disclosure')
    check(e(f'document.querySelector({q(row(trip))}).children.length===5&&!document.querySelector({q(row(trip))}).innerText.includes("%")'),'no parent progress clutter or added column')
    original=layout(flight)
    check(original['children']==5 and abs(original['center']-original['slotCenter'])<1,'task marker reuses centered disclosure gutter without extra controls')
    check(len({layout(id)['name'] for id in tasks})==1,'sibling task names align')
    select(normal)
    e('window.sidebarPulses=[];window.sidebarOriginalPulse=motion.taskComplete.bind(motion);motion.taskComplete=(node,delay)=>{sidebarPulses.push(node?.dataset.entryId);return sidebarOriginalPulse(node,delay)}')
    click(marker(flight))
    check(checked(flight)=='true','native sidebar click completes task')
    check(e(f'selectedNode.dataset.entryId==={q(flight)}&&!hierarchySidebar.collapsed'),'checkbox completion focuses task and retains desktop sidebar')
    check(e(f'entries.get({q(flight)}).completed&&nodes.get({q(flight)}).dataset.taskComplete==="true"&&nodes.get({q(flight)}).style.getPropertyValue("--task-ratio")==="1"'),'sidebar completion lights up the same Universe CB')
    check(e(f'taskStates.get({q(trip)}).ratio===.25&&nodes.get({q(trip)}).style.getPropertyValue("--task-ratio")==="0.25"'),'sidebar completion updates direct parent progress and artwork')
    check(e(f'!!nodes.get({q(trip)}).querySelector(".task-ring-value")&&sidebarPulses.includes({q(flight)})'),'progress ring retained and shared completion pulse fires')
    check(layout(flight)['name']==original['name'] and layout(flight)['columns']==original['columns'],'completion never shifts task label or columns')
    check(e(f'document.querySelector({q(marker(flight))}).getAttribute("aria-label")==="Mark Buy flight as incomplete"'),'completed marker has an actionable accessible name')
    check(e(f'JSON.parse(localStorage.getItem("galaxy:user-data")).entries.find(x=>x.id==={q(flight)}).completed'),'sidebar completion persists through existing repository')
    # Inspect actual browser accessibility semantics, not just DOM attributes.
    document=cdp.call('DOM.getDocument')['root']['nodeId']
    node=cdp.call('DOM.querySelector',nodeId=document,selector=marker(flight))['nodeId']
    ax=cdp.call('Accessibility.getPartialAXTree',nodeId=node)['nodes'][0]
    check(ax.get('role',{}).get('value')=='checkbox' and ax.get('name',{}).get('value')=='Mark Buy flight as incomplete' and any(p['name']=='checked' and p['value']['value']=='true' for p in ax.get('properties',[])),'browser accessibility tree exposes name, checkbox role and checked state')
    click(row(flight)+' .tree-name')
    check(e(f'selectedNode.dataset.entryId==={q(flight)}&&entries.get({q(flight)}).completed'),'task name still selects without toggling completion')
    check(e('document.getElementById("content-task-done").checked'),'Contents Done matches sidebar completion on selection')
    pulse_count=e('sidebarPulses.length')
    click(marker(flight))
    check(checked(flight)=='false' and e('!document.getElementById("content-task-done").checked'),'sidebar uncheck updates selected Contents Done')
    check(e(f'taskStates.get({q(trip)}).ratio===0&&nodes.get({q(flight)}).dataset.taskComplete==="false"&&sidebarPulses.length==={pulse_count}'),'uncheck reverses progress/visuals without celebration')
    click('#content-task-done')
    check(checked(flight)=='true','Contents Done updates sidebar marker immediately')
    select(flight)
    e(f'document.querySelector({q(marker(flight))}).focus()')
    cdp.call('Input.dispatchKeyEvent',type='keyDown',key=' ',code='Space',windowsVirtualKeyCode=32)
    cdp.call('Input.dispatchKeyEvent',type='keyUp',key=' ',code='Space',windowsVirtualKeyCode=32)
    e('applicationCommandTail')
    check(checked(flight)=='false','desktop Space toggles focused sidebar checkbox')
    check(e(f'document.activeElement===document.querySelector({q(marker(flight))})&&document.activeElement.matches(":focus-visible")&&parseFloat(getComputedStyle(document.activeElement).outlineWidth)>0'),'keyboard focus remains visible after saving')
    cdp.call('Input.dispatchKeyEvent',type='keyDown',key=' ',code='Space',windowsVirtualKeyCode=32)
    cdp.call('Input.dispatchKeyEvent',type='keyUp',key=' ',code='Space',windowsVirtualKeyCode=32)
    e('applicationCommandTail')
    check(checked(flight)=='true','repeated keyboard toggle works without refocusing')
    # Pending and rejected writes keep the durable checked state and control focus.
    e('window.sidebarUpdate=universeRepository.updateTask;window.sidebarHold=null;universeRepository.updateTask=(...args)=>new Promise(resolve=>{sidebarHold=()=>resolve(sidebarUpdate(...args))})')
    e(f'document.querySelector({q(marker(flight))}).click()')
    wait_for('sidebarHold!==null')
    check(e(f'document.querySelector({q(marker(flight))}).getAttribute("aria-disabled")==="true"&&document.querySelector({q(marker(flight))}).getClientRects().length>0'),'pending completion keeps marker visible and exposes disabled state')
    check(checked(flight)=='true','pending write keeps durable checked state')
    e('sidebarHold();applicationCommandTail;universeRepository.updateTask=sidebarUpdate')
    wait_for('!taskWritePending')
    check(checked(flight)=='false','pending write publishes through shared completion path')
    e('universeRepository.updateTask=async()=>{throw new Error("Test sidebar save failure")}')
    e(f'document.querySelector({q(marker(flight))}).click();applicationCommandTail')
    check(checked(flight)=='false' and e('!document.getElementById("content-task-error").hidden'),'failed sidebar save restores durable state and uses shared error reporting')
    select(normal)
    e(f'document.querySelector({q(marker(flight))}).click();applicationCommandTail')
    check(checked(flight)=='false' and e('!storageStatus.hidden&&storageStatus.textContent.includes("Test sidebar save failure")'), 'sidebar save failure stays visible when normal Contents is selected')
    e('universeRepository.updateTask=sidebarUpdate;storageStatus.hidden=true')
    select(flight)
    for id in tasks: click(marker(id))
    check(e(f'taskStates.get({q(trip)}).complete&&sidebarPulses.includes({q(trip)})'),'final sidebar task completes and pulses parent')
    shot('sidebar-tasks-desktop')
    # Role changes reuse the same gutter node, restoring ordinary disclosure.
    e(f'moveSidebarEntries({{ids:[{q(flight)}],activeId:{q(flight)}}},{q(root)})')
    check(e(f'!document.querySelector({q(marker(flight))}).hasAttribute("aria-checked")&&document.querySelector({q(marker(flight))}).disabled'),'moving task out restores normal childless disclosure')
    e(f'moveSidebarEntries({{ids:[{q(flight)}],activeId:{q(flight)}}},{q(trip)})')
    check(checked(flight)=='true','moving task back restores retained completion marker')
    select(trip)
    click(marker(trip))
    check(e(f'!hierarchySidebar.expanded.has({q(trip)})'),'Task List disclosure still collapses branch')
    click(marker(trip))
    check(e(f'hierarchySidebar.expanded.has({q(trip)})'),'Task List disclosure still expands branch')
    for width,height in [(360,800),(390,844),(430,932)]:
        cdp.call('Emulation.setDeviceMetricsOverride',width=width,height=height,deviceScaleFactor=1,mobile=True)
        cdp.call('Emulation.setTouchEmulationEnabled',enabled=True,maxTouchPoints=5)
        wait_for('hierarchySidebar.narrow')
        e('new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))')
        select(flight)
        start=checked(flight)
        before=layout(flight)
        check(before['button']==[44,44] and before['row']==44 and before['nameClear'],'mobile target is 44px with unchanged row height and no name overlap: '+str(width))
        check(abs(before['center']-before['slotCenter'])<1 and len({layout(id)['name'] for id in tasks})==1,'mobile marker stays centered in existing gutter; siblings align: '+str(width))
        click(marker(flight),True)
        check(checked(flight)!=start,'touch checkbox toggles through shared completion: '+str(width))
        e('hierarchySidebar.setCollapsed(false)')
        check(layout(flight)['name']==before['name'],'touch completion never shifts task names: '+str(width))
        check(e(f'(()=>{{const r=document.querySelector({q(row(flight))}),n=r.querySelector(".tree-name").getBoundingClientRect(),a=r.querySelector(".tree-add").getBoundingClientRect(),m=r.querySelector(".tree-more").getBoundingClientRect();return r.children.length===5&&n.right<=a.left&&a.right<=m.left&&a.width===44&&m.width===44}})()'),'existing +/More controls remain separate and reachable: '+str(width))
        click(row(flight)+' .tree-add',True)
        check(e('[...addMenu.querySelectorAll("button:not([hidden])")].map(b=>b.textContent).join("|")==="Take Photo|Photo Gallery"'),'task + retains capture actions: '+str(width))
        e('closeContentMenus()')
        click(row(flight)+' .tree-more',True)
        check(e(f'!contextMenu.hidden&&contextEntryId==={q(flight)}'),'task More retains canonical target: '+str(width))
        e('closeContextMenu()')
        shot('sidebar-tasks-'+str(width))
        start=checked(flight)
        click(row(flight)+' .tree-name',True)
        check(e(f'hierarchySidebar.collapsed&&selectedNode.dataset.entryId==={q(flight)}') and checked(flight)==start,'task name keeps mobile navigation without toggling: '+str(width))
    # A long checklist scrolls naturally, even when a gesture starts on a marker.
    e(f'hierarchySidebar.setCollapsed(false);createChildEntry({q(root)},true);fields[0].value="Long checklist";document.getElementById("task-list-tasks").value=Array.from({{length:30}},(_,i)=>"Task "+i).join(String.fromCharCode(10));form.requestSubmit();applicationCommandTail')
    wait_for('!dialog.open&&!formSaveBusy')
    longlist=e('selectedNode.dataset.entryId')
    e(f'hierarchySidebar.expanded=new Set([{q(root)},{q(longlist)}]);hierarchySidebar.render();hierarchySidebar.setCollapsed(false);hierarchySidebar.tree.scrollTop=0')
    first=e(f'galaxyModel.childrenOf(entries,{q(longlist)})[0].id')
    e(f'document.querySelector({q(marker(first))}).scrollIntoView({{block:"center"}})')
    before_scroll=e('hierarchySidebar.tree.scrollTop')
    p=e(f'(()=>{{const r=document.querySelector({q(marker(first))}).getBoundingClientRect();return {{x:r.x+r.width/2,y:r.y+r.height/2}}}})()')
    cdp.call('Input.dispatchTouchEvent',type='touchStart',touchPoints=[p])
    for dy in [15,35,65,95,125]: cdp.call('Input.dispatchTouchEvent',type='touchMove',touchPoints=[dict(x=p['x'],y=p['y']-dy)])
    cdp.call('Input.dispatchTouchEvent',type='touchEnd',touchPoints=[])
    wait_for(f'hierarchySidebar.tree.scrollTop>{before_scroll}')
    check(checked(first)=='false','mobile scrolling from checkbox does not complete task')
    check(e('hierarchySidebar.tree.scrollHeight>hierarchySidebar.tree.clientHeight'),'long checklist keeps normal sidebar scrolling')
    e(f'document.querySelector({q(marker(first))}).click();applicationCommandTail')
    check(e(f'entries.get({q(first)}).completed'),'offscreen task completion uses same action')
    cdp.call('Page.reload',ignoreCache=True)
    wait_for('document.readyState==="complete"&&typeof hierarchySidebar!=="undefined"&&entries.size>0')
    e(f'hierarchySidebar.expanded=new Set([{q(root)},{q(longlist)}]);hierarchySidebar.render()')
    check(checked(first)=='true','sidebar checked state survives real browser reload')
    check(not cdp.errors,'no sidebar completion browser exceptions')
